const { chromium } = require('C:/Users/user/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const external=[];page.on('request',r=>{if(/^https?:/.test(r.url())) external.push(r.url());});
 const file=path.resolve(__dirname,'../회의실-예약시스템-시각기획안.html');
 await page.goto(pathToFileURL(file).href);
 console.log('Page loaded');
 await page.evaluate(()=>{document.querySelectorAll('img[loading]').forEach(i=>i.loading='eager');});
 await page.waitForFunction(()=>[...document.images].filter(i=>i.src).every(i=>i.complete&&i.naturalWidth>0));
 console.log('Images loaded');
 const check=(value,message)=>{if(!value)throw Error(message);};
 check(await page.locator('.chapter').count()===7,'7 chapters');
 check(await page.locator('.shot img').count()===5,'5 mockups');
 await page.getByRole('tab',{name:'모집 만료'}).click();
 check(await page.locator('#case-expire').isVisible(),'expiry tab');
 await page.getByRole('tab',{name:'모집 만료'}).press('ArrowRight');
 check(await page.locator('#case-refill').isVisible(),'keyboard tab');
 await page.locator('#shared').fill('3');await page.locator('#shared').dispatchEvent('input');
 check(await page.locator('#fair-result').evaluate(e=>e.classList.contains('blocked')),'75% and 30 min blocked');
 await page.locator('#gap').selectOption('60');
 check(!await page.locator('#fair-result').evaluate(e=>e.classList.contains('blocked')),'60 min allowed');
 await page.locator('#shared').fill('2');await page.locator('#shared').dispatchEvent('input');await page.locator('#gap').selectOption('30');
 await page.locator('.zoom').first().click();check(await page.locator('#image-dialog').isVisible(),'image dialog');
 await page.keyboard.press('Escape');check(!await page.locator('#image-dialog').isVisible(),'escape closes');
 await page.getByRole('tab',{name:'정상 확정'}).click();
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:path.resolve(__dirname,'desktop-preview.png')});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'desktop overflow');
 await page.locator('#system').scrollIntoViewIfNeeded();await page.screenshot({path:path.resolve(__dirname,'system-preview.png')});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:path.resolve(__dirname,'mobile-preview.png')});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
 await page.locator('.zoom').last().click();check(await page.locator('#image-dialog').isVisible(),'mobile dialog');await page.keyboard.press('Escape');
 await page.emulateMedia({media:'print'});check(await page.locator('#case-expire').isVisible(),'print all scenarios');
 const links=await page.locator('.source-list a').evaluateAll(as=>as.map(a=>decodeURIComponent(new URL(a.href).pathname).replace(/^\/([A-Za-z]:)/,'$1')));
 check(links.every(p=>fs.existsSync(p)),'source links resolve');
 check(errors.length===0,'JS errors: '+errors.join(','));check(external.length===0,'unexpected network');
 console.log(JSON.stringify({chapters:7,mockups:5,desktop:'1440x1000',mobile:'390x844',checks:['tabs','keyboard','fairness boundaries','image modal','Escape','no overflow','print scenarios','source links','offline'],errors,external},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
